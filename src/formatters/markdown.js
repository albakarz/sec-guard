/**
 * GitHub Flavored Markdown Formatter
 * Ideal for PR comments, agent artifacts, or export documents
 */

export function formatMarkdown(scanResult) {
  const { findings, filesScanned, totalLinesScanned, activeRulesCount, durationMs } = scanResult;

  let md = '# 🛡️ Security & Compliance Audit Report\n\n';
  md += `*Generated by **sec-guard** on ${new Date().toUTCString()}*\n\n`;

  md += '## 📈 Executive Summary\n\n';
  md += '| Metric | Value |\n';
  md += '| :--- | :--- |\n';
  md += `| **Files Scanned** | ${filesScanned} |\n`;
  md += `| **Lines Inspected** | ${totalLinesScanned} |\n`;
  md += `| **Active Rules** | ${activeRulesCount} |\n`;
  md += `| **Scan Duration** | ${durationMs} ms |\n`;
  md += `| **Total Issues Found** | ${findings.length} |\n\n`;

  if (findings.length === 0) {
    md += '✅ **No security vulnerabilities or compliance red flags detected.**\n';
    return md;
  }

  // Count by severity
  const counts = {};
  for (const f of findings) {
    counts[f.severity] = (counts[f.severity] || 0) + 1;
  }

  md += '### Severity Distribution\n\n';
  md += '| Severity | Count |\n';
  md += '| :--- | :--- |\n';
  for (const [sev, count] of Object.entries(counts)) {
    md += `| **${sev}** | ${count} |\n`;
  }
  md += '\n---\n\n';

  md += '## 🔍 Detailed Findings\n\n';

  findings.forEach((f, idx) => {
    md += `### ${idx + 1}. [${f.severity}] \`${f.ruleId}\`\n\n`;
    md += `- **File:** \`${f.file}\` (Line ${f.line})\n`;
    md += `- **Category:** ${f.category || 'Security'}\n`;
    if (f.cwe) md += `- **CWE:** [${f.cwe}](https://cwe.mitre.org/data/definitions/${f.cwe.replace('CWE-', '')}.html)\n`;
    md += `- **Description:** ${f.message}\n\n`;
    md += '**Vulnerable Code:**\n';
    md += '```\n' + f.codeSnippet + '\n```\n\n';
    if (f.remediation) {
      md += `**Recommended Remediation:**\n> ${f.remediation}\n\n`;
    }
  });

  return md;
}

